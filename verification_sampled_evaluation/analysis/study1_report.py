#!/usr/bin/env python3
"""Study 1 tables (DESIGN.md 4.8) from results/study1/outcomes.jsonl and the reference records.
Writes results/study1/*.csv and results/study1/tables.md. No Ocean-MCP import."""
from __future__ import annotations

import csv
import gzip
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

PKG = Path(__file__).resolve().parent.parent
REF = PKG / "reference/results/w49_7"
OUT = PKG / "results/study1"
PREV = {"2026-08-16", "2026-08-17"}
CLASSES = ["correct_comparison", "correct_refusal", "refusal_reason_differs", "false_refusal",
           "undetected_problem", "not_eligible", "other_discrepancy", "invalid_session", "not_run"]


def period(c):
    if c["product"] == "2d":
        return "2D"
    return "3D v3.1 (LMSL)" if c["version"].startswith("3.1") else "3D v2.1 (NAVD88)"


def defects(c) -> list[str]:
    d = []
    for scope, counts in (("window", c["model_counts_window"]), ("series", c["model_counts_all"])):
        for k in ("fill", "dry", "nonfinite", "implausible", "outside_valid_range"):
            if counts.get(k):
                d.append(f"model_{k}_{scope}")
    if c["model_code_like_all"]:
        d.append("model_code_like_series")
    if c["reference_datum_status"] not in ("label_matches_documentation", "documented_generic_label"):
        d.append(f"datum_{c['reference_datum_status']}")
    if c["duplicate_id"]:
        d.append("identity_duplicate_id")
    if c["substring_collision"]:
        d.append("identity_substring_collision")
    o = c["observations"]
    oc = o.get("counts", {})
    for k in ("missing", "nonfinite", "implausible"):
        if oc.get(k):
            d.append(f"obs_{k}")
    if oc.get("flagged_any"):
        d.append("obs_flagged")
    if c["paired_datum_published"] is False:
        d.append("obs_paired_datum_not_published")
    if c["metadata_disagrees_with_served"]:
        d.append("obs_metadata_disagrees_with_served")
    if c["expected"]["expected"] == "not_eligible":
        for r in c["expected"]["reasons"]:
            d.append(f"obs_{r}")
    n = c["statistics"].get("n", 0)
    if c["expected"]["expected"] == "compare" and n < 0.8 * 497:
        d.append("obs_pairs_below_80pct")
    return d


def write_csv(name, rows, fields):
    with open(OUT / name, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=fields, extrasaction="ignore")
        w.writeheader()
        for r in rows:
            w.writerow(r)


def md_table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" if i == 0 else "---:" for i in range(len(head))) + "|"]
    out += ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]
    return "\n".join(out)


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    refs = {json.loads(x)["case_id"]: json.loads(x) for x in (REF / "cases.jsonl").read_text().splitlines()}
    outs = {json.loads(x)["case_id"]: json.loads(x) for x in (OUT / "outcomes.jsonl").read_text().splitlines()}
    files = [json.loads(x) for x in (REF / "files.jsonl").read_text().splitlines()]
    md = ["# Study 1 tables (generated by analysis/study1_report.py)\n"]

    # T1 counts by class per period: main sample (not previously seen), previously seen, all
    for label, keep in (("sample without previously seen cycles", lambda c: c["cycle"][:10] not in PREV),
                        ("previously seen cycles (2026-08-16, 2026-08-17)", lambda c: c["cycle"][:10] in PREV),
                        ("all cycles", lambda c: True)):
        cnt = defaultdict(Counter)
        for cid, c in refs.items():
            if keep(c):
                cnt[period(c)][outs[cid]["class"]] += 1
        per = ["3D v2.1 (NAVD88)", "3D v3.1 (LMSL)", "2D"]
        rows = [[k] + [cnt[p][k] for p in per] + [sum(cnt[p][k] for p in per)] for k in CLASSES if any(cnt[p][k] for p in per)]
        rows.append(["**total**"] + [sum(cnt[p].values()) for p in per] + [sum(sum(cnt[p].values()) for p in per)])
        md += [f"## Outcome classes by product: {label}\n", md_table(["class"] + per + ["all"], rows), ""]

    # sub-labels
    sub = Counter((outs[c]["class"], outs[c]["sub"]) for c in outs)
    md += ["## Sub-labels\n", md_table(["class", "sub-label", "cases"], [[a, b or "", n] for (a, b), n in sorted(sub.items())]), ""]

    # distinct stations and files per class
    rows = []
    for k in CLASSES:
        cs = [refs[c] for c in outs if outs[c]["class"] == k]
        if cs:
            rows.append([k, len(cs), len({c["station_id"] for c in cs}), len({(c["product"], c["cycle"]) for c in cs})])
    md += ["## Cases, distinct stations and distinct files per class\n", md_table(["class", "cases", "stations", "files"], rows), ""]

    # by defect class
    dd = defaultdict(list)
    for cid, c in refs.items():
        for d in defects(c):
            dd[d].append(cid)
    rows, csvrows = [], []
    for d, cids in sorted(dd.items()):
        cc = Counter(outs[c]["class"] for c in cids)
        rows.append([d, len(cids), len({refs[c]["station_id"] for c in cids}), len({(refs[c]["product"], refs[c]["cycle"]) for c in cids}),
                     ", ".join(f"{k} {v}" for k, v in cc.most_common())])
        csvrows.append({"defect": d, "cases": len(cids), "stations": rows[-1][2], "files": rows[-1][3], **cc})
    md += ["## Defect classes (reference properties) with the tool's outcome\n",
           md_table(["defect", "cases", "stations", "files", "tool outcome classes"], rows), ""]
    write_csv("by_defect.csv", csvrows, ["defect", "cases", "stations", "files"] + CLASSES)

    # by cycle and by station (CSV)
    bc = defaultdict(Counter)
    bs = defaultdict(Counter)
    for cid, c in refs.items():
        bc[(c["product"], c["cycle"][:10])][outs[cid]["class"]] += 1
        bs[(c["product"], c["station_id"])][outs[cid]["class"]] += 1
    write_csv("by_cycle.csv", [{"product": p, "cycle": d, **v} for (p, d), v in sorted(bc.items())], ["product", "cycle"] + CLASSES)
    write_csv("by_station.csv", [{"product": p, "station_id": s, **v} for (p, s), v in sorted(bs.items())], ["product", "station_id"] + CLASSES)
    rows = [[p, d] + [v[k] for k in CLASSES[:7]] for (p, d), v in sorted(bc.items())]
    md += ["## By cycle\n", md_table(["product", "cycle"] + CLASSES[:7], rows), ""]

    # individual listings
    lst = []
    for cid in sorted(outs):
        o = outs[cid]
        if o["class"] in ("false_refusal", "undetected_problem", "other_discrepancy", "refusal_reason_differs"):
            ev = o["evidence"]
            lst.append({"case_id": cid, "class": o["class"], "sub": o["sub"], "expected": o["expected"],
                        "reference_reasons": ",".join(refs[cid]["expected"]["reasons"]),
                        "tool_reason": ev.get("tool_reason"), "tool_text": (ev.get("tool_text") or "")[:300].replace("\n", " "),
                        "tool_pairing": json.dumps(ev.get("tool_pairing")), "requested": json.dumps(ev.get("requested_coops")),
                        "n_tool": ev.get("n_tool"), "n_ref": ev.get("n_ref"), "stat_diffs": json.dumps(ev.get("stat_diffs")),
                        "model_excluded": json.dumps(ev.get("model_excluded")), "nearest": ev.get("tool_nearest_pairs")})
    write_csv("individual_cases.csv", lst, list(lst[0].keys()) if lst else ["case_id"])
    md += [f"## Individually listed cases: {len(lst)} (full evidence in individual_cases.csv)\n"]
    grp = Counter((x["class"], x["sub"]) for x in lst)
    md += [md_table(["class", "sub-label", "cases"], [[a, b, n] for (a, b), n in sorted(grp.items())]), ""]

    # 20-100 m band
    band = [json.loads(x) for x in (REF / "band_20_100m.jsonl").read_text().splitlines()]
    agg = defaultdict(lambda: {"n": 0, "in_window": 0, "min": 1e9, "max": -1e9, "files": set()})
    for b in band:
        a = agg[(b["product"], b["station_name"])]
        a["n"] += 1
        a["in_window"] += b["in_window"]
        a["min"] = min(a["min"], b["value_m"])
        a["max"] = max(a["max"], b["value_m"])
        a["files"].add(b["cycle"])
    rows = [[p, n, v["n"], v["in_window"], f"{v['min']:.2f}", f"{v['max']:.2f}", len(v["files"])] for (p, n), v in sorted(agg.items())]
    md += [f"## Model values with 20 m <= |v| <= 100 m: {len(band)} values (all records of all sampled files)\n",
           md_table(["product", "station record", "values", "in window", "min", "max", "files"], rows), ""]
    between = [b for b in band if 30 < abs(b["value_m"]) < 50]
    md += [f"Values with 30 m < |v| < 50 m (the reference excludes, the tool keeps): {len(between)}; "
           f"of these in a window: {sum(b['in_window'] for b in between)}.\n"]

    # S9: bound sensitivity, by in-window values of mapped cases
    def affected(lo, hi):
        hits = {(b["product"], b["cycle"], b["station_index"]) for b in band if b["in_window"] and lo < abs(b["value_m"]) <= hi}
        return sum(1 for c in refs.values() if (c["product"], c["cycle"], c["record_index"]) in hits)
    md += ["## S9: cases whose in-window values change class under another bound\n",
           md_table(["bound", "cases with in-window values that the bound reclassifies"],
                    [["20 m (vs 30)", affected(20, 30)], ["50 m (vs 30)", affected(30, 50)], ["100 m (vs 30)", affected(30, 100)]]), ""]

    # 0.2.0 contrast
    ct = defaultdict(Counter)
    for cid, o in outs.items():
        c20 = o["contrast_020"]
        ct[period(refs[cid])][(c20.get("expected"), c20.get("decision"), c20.get("pairing"))] += 1
    rows = [[p, e, d, pr, n] for p, v in sorted(ct.items()) for (e, d, pr), n in sorted(v.items(), key=lambda x: str(x))]
    md += ["## stofs-mcp 0.2.0 contrast (decision and pairing only)\n", md_table(["product", "expected", "0.2.0 decision", "pairing", "cases"], rows), ""]

    # preliminary observations
    pre = [c for c in refs.values() if c["statistics"].get("n")]
    anyp = sum(1 for c in pre if c["observations"]["counts"]["preliminary"] > 0)
    allv = sum(1 for c in pre if c["observations"]["counts"]["preliminary"] == 0)
    md += [f"## Preliminary observations\n\nCases with pairs: {len(pre)}; with any preliminary paired observation: {anyp}; "
           f"all paired observations verified: {allv}.\n"]

    # versions against the documented date
    md += ["## File versions against the portal date (2026-08-17 12z)\n",
           md_table(["product", "cycle", "version", "disagrees with portal date"],
                    [[f["product"], f["cycle"][:10], f["version"], f["version_disagrees_with_portal_date"]] for f in files
                     if f["version_disagrees_with_portal_date"] or f["cycle"][:10] in ("2026-08-15", "2026-08-16", "2026-08-17")]), ""]

    # coops-mcp datums session: does the MCP route show MSL / NAVD88 as the metadata lists them, and the epoch?
    p = PKG / "run_log/sessions/coops011/datums/transcript.json.gz"
    if p.exists():
        sys.path.insert(0, str(PKG / "reference"))
        import archive_io as aio
        from classify import load_datums
        dm = load_datums([aio.Archive(PKG / "data/archive/meta")])
        tr = json.load(gzip.open(p, "rt"))
        rows = Counter()
        for call in tr["calls"]:
            text = "".join(x.get("text", "") for x in call["content"] if x.get("type") == "text")
            sid = call["arguments"]["station_id"]
            pub = set(dm.get(sid, {}).get("published", []))
            shows = {d: bool(re.search(r"\|\s*" + d + r"\s*\|\s*-?\d", text)) for d in ("MSL", "NAVD88")}
            epoch = bool(re.search(r"(?i)\bepoch\b|\b(19|20)\d\d\s*-\s*(19|20)\d\d\b", text))
            rows[(shows["MSL"] == ("MSL" in pub), shows["NAVD88"] == ("NAVD88" in pub), epoch, call["valid"])] += 1
        md += ["## coops-mcp 0.1.1 coops_get_datums (one session, every station)\n",
               md_table(["MSL shown as in metadata", "NAVD88 shown as in metadata", "epoch stated", "call valid", "stations"],
                        [[a, b, e, v, n] for (a, b, e, v), n in sorted(rows.items(), key=str)]), "",
               f"Session valid: {tr['valid']}; calls: {len(tr['calls'])}.\n"]
    (OUT / "tables.md").write_text("\n".join(md) + "\n")
    print(f"wrote {OUT / 'tables.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
