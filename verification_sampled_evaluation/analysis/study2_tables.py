#!/usr/bin/env python3
"""Format results/study2/results.json and results/a1 as markdown (results/study2/tables.md)."""
import csv
import json
import sys
from pathlib import Path

PKG = Path(__file__).resolve().parent.parent
R = json.loads((PKG / "results/study2/results.json").read_text())
A1 = json.loads((PKG / "results/a1/datum_consistency.json").read_text())


def f(x, d=3):
    return "—" if x is None else (f"{x:+.{d}f}" if isinstance(x, (int, float)) else str(x))


def ci(v, d=2):
    return "—" if not v or v[0] != v[0] else f"[{v[0]:+.{d}f}, {v[1]:+.{d}f}]"


def row(name, a):
    x = a.get("X", a) if "X" in a else a
    return [name, x.get("n_stations"), f(x.get("slope"), 2), ci(x.get("slope_ci")), f(x.get("intercept")),
            ci(x.get("intercept_ci"), 3), f(x.get("offset_sd")), f(x.get("level_test_mean_bias_plus_offset")),
            ci(x.get("level_test_ci"), 3), f(x.get("carried_fraction"), 2), ci(x.get("carried_fraction_ci")),
            a.get("verdict_A2", x.get("verdict")), ("robust" if a.get("robust") else "fragile") if "robust" in a else "—"]


def md(head, rows):
    return "\n".join(["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] +
                     ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


H = ["analysis", "stations", "slope", "95% CI", "intercept (m)", "95% CI", "SD(X) (m)", "level B+X (m)", "95% CI",
     "carried f", "95% CI", "verdict", "cluster"]
out = ["# Study 2 tables (generated by analysis/study2_tables.py)\n", "## Regressions\n"]
rows = [row(k, v) for k, v in R.items() if isinstance(v, dict) and ("X" in v or "slope" in v)]
out += [md(H, rows), "", "## Sensitivity runs\n", md(H, [row(k, v) for k, v in R["sensitivity"].items()]), ""]
p = R["primary"]
out += ["## Primary analysis, A2 detail\n",
        md(["offset", "level test", "95% CI", "carried f", "95% CI", "boundary mean bias", "boundary mean offset", "verdict"],
           [[k, f(v.get("level_test_mean_bias_plus_offset")), ci(v.get("level_test_ci"), 3), f(v.get("carried_fraction"), 2),
             ci(v.get("carried_fraction_ci")), f(v.get("boundary_mean_bias")), f(v.get("boundary_mean_offset_xbar_b")),
             (p.get("verdicts_by_offset") or {}).get(k, v.get("verdict"))] for k, v in (("X", p["X"]), ("O12_pre", p["O12_pre"]))]),
        f"\nA2 verdict: **{p.get('verdict_A2')}**; cluster bootstrap: {p['X'].get('verdict_cluster_bootstrap')}.\n"]
out += ["## A3: mean bias per cycle (NTDE stations entering that cycle)\n",
        md(["product", "cycle", "stations", "mean bias all (m)", "boundary stations", "mean bias boundary (m)"],
           [[r["product"], r["cycle"], r["n_stations"], f(r["mean_bias_all"]), r["n_boundary"], f(r["mean_bias_boundary"])]
            for r in R["A3_per_cycle"]]), ""]
out += ["## A4: Boston 8443970\n",
        md(["product", "cycle", "paired datum", "n", "bias (m)", "model mean (m)", "observed mean (m)", "expected"],
           [[r["product"], r["cycle"], r["paired_datum"], r["n"], f(r["bias"]), f(r["model_mean"]), f(r["obs_mean"]), r["expected"]]
            for r in R["A4_boston"]]), ""]
out += ["## A1: datum consistency d = (CO-OPS MSL) − (VDatum LMSL)\n",
        f"Boston check: offline {A1['boston_check']['offline']:.6f} m against the Boston package's "
        f"{A1['boston_check']['boston_package']:.6f} m (same within 1e-6: {A1['boston_check']['same_within_1e-6_m']}).\n",
        f"Stations with MSL and NAVD88: {A1['n_stations_both_datums']}; evaluated {A1['n_evaluated']}; not evaluated "
        f"{A1['n_not_evaluated']}. Median d {A1['median_m']:+.4f} m, SD {A1['sd_m']:.4f} m; largest |d| "
        f"{A1['largest_abs']['d_m']:+.3f} m at {A1['largest_abs']['station_id']} {A1['largest_abs']['name']} "
        f"(epoch {A1['largest_abs']['epoch']}); |d| <= 0.03 m at {A1['n_abs_le_0_03']}.\n",
        md(["not evaluated", "reason"], [[s["station_id"] + " " + str(s.get("name", "")), s["reason"]] for s in A1["not_evaluated"]]), ""]
with open(PKG / "results/a1/datum_consistency.csv", "w", newline="") as fh:
    w = csv.DictWriter(fh, fieldnames=list(A1["rows"][0].keys()))
    w.writeheader()
    w.writerows(A1["rows"])
(PKG / "results/study2/tables.md").write_text("\n".join(out) + "\n")
print("wrote results/study2/tables.md")
sys.exit(0)
